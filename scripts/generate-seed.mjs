// Generates supabase/seed.sql from src/services/events/dev-fixtures.json.
// Dates are computed in SQL relative to the day the seed runs, in each
// event's own timezone, so the sample data does not go stale.
// Usage: node scripts/generate-seed.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const { events } = JSON.parse(readFileSync(new URL('../src/services/events/dev-fixtures.json', import.meta.url)));
const q = (v) => (v == null ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const n = (v) => (v == null ? 'null' : String(v));

const rows = events.map((e) => {
  const localDate = `((now() at time zone ${q(e.tz)})::date + ${e.dayOffset})`;
  const startsAt = e.localTime ? `((${localDate} + time ${q(e.localTime)}) at time zone ${q(e.tz)})` : 'null';
  const endsAt = e.localTime && e.durationMin ? `(${startsAt} + interval '${e.durationMin} minutes')` : 'null';
  return `  (${q(e.id)}, 'atlas-dev-fixture', ${q(e.id)}, ${q(e.name)}, 'Development sample event. This is not a real listing.',
   ${q(e.category)}, ${q(e.genre)}, ${q(e.venue)}, ${q(e.address)}, ${q(e.city)}, ${q(e.region)}, ${q(e.country)},
   ${n(e.lat)}, ${n(e.lng)}, ${startsAt}, ${endsAt}, ${localDate}, ${e.localTime ? q(e.localTime) : 'null'}, ${q(e.tz)},
   ${q(e.open)}, ${q(e.close)}, ${n(e.priceMin)}, ${n(e.priceMax)}, ${q(e.currency)}, 'Atlas development fixtures', true)`;
});

const sql = `-- GENERATED by scripts/generate-seed.mjs — do not edit by hand.
-- DEVELOPMENT SAMPLE DATA ONLY: clearly flagged with is_dev_fixture = true and
-- "Sample:" names. Do NOT load into production.
insert into public.events (
  id, provider, external_id, name, description, category, genre, venue_name, address, city, region, country,
  latitude, longitude, starts_at, ends_at, start_local_date, start_local_time, timezone,
  venue_open_time, venue_close_time, price_min, price_max, currency, source_name, is_dev_fixture)
values
${rows.join(',\n')}
on conflict (provider, external_id) do update set
  starts_at = excluded.starts_at, ends_at = excluded.ends_at,
  start_local_date = excluded.start_local_date, last_checked_at = now();
`;
writeFileSync(new URL('../supabase/seed.sql', import.meta.url), sql);
console.log(`Wrote supabase/seed.sql with ${events.length} sample events`);
