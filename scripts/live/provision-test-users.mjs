/**
 * Provision dedicated LIVE TEST accounts in the linked Supabase project.
 *
 *   node scripts/live/provision-test-users.mjs            # create/refresh users A, B, C
 *   node scripts/live/provision-test-users.mjs --delete   # delete them (cascades their data)
 *
 * - The project's secret (service) key is obtained from the logged-in Supabase
 *   CLI and kept IN MEMORY ONLY. It is never printed or written anywhere.
 * - Users are created through the Auth Admin API with email_confirm=true, so no
 *   emails are sent. Emails use the reserved example.com domain.
 * - Fresh random passwords are written to .env.live.local (gitignored via
 *   `.env.*.local`) for the live test suites to read.
 * - A single clearly-labelled sample event (is_dev_fixture=true, provider
 *   'atlas-live-test', mid-Atlantic coordinates) is upserted so save-event flows
 *   can be tested independently of Ticketmaster.
 */
import { execFileSync } from 'node:child_process';
import { randomBytes } from 'node:crypto';
import { readFileSync, writeFileSync, existsSync, unlinkSync } from 'node:fs';
import { createClient } from '@supabase/supabase-js';
import WebSocket from 'ws'; // Node 20 has no native WebSocket (needed by supabase-js realtime)

const ref = readFileSync('supabase/.temp/project-ref', 'utf8').trim();
const url = `https://${ref}.supabase.co`;
const keys = JSON.parse(execFileSync('supabase', ['projects', 'api-keys', '--project-ref', ref, '-o', 'json'], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }));
const service = keys.find((k) => k.name === 'service_role')?.api_key ?? keys.find((k) => k.type === 'secret')?.api_key;
if (!service) throw new Error('Could not obtain a service key from the Supabase CLI (are you logged in?)');
const admin = createClient(url, service, { auth: { persistSession: false, autoRefreshToken: false }, realtime: { transport: WebSocket } });

const USERS = ['a', 'b', 'c'].map((id) => ({ id, email: `atlas-live-${id}@example.com`, username: `atlas_live_${id}` }));

async function findUser(email) {
  for (let page = 1; page < 50; page++) {
    const { data, error } = await admin.auth.admin.listUsers({ page, perPage: 200 });
    if (error) throw error;
    const hit = data.users.find((u) => u.email === email);
    if (hit) return hit;
    if (data.users.length < 200) return null;
  }
  return null;
}

if (process.argv.includes('--delete')) {
  for (const u of USERS) {
    const found = await findUser(u.email);
    if (found) {
      const { error } = await admin.auth.admin.deleteUser(found.id);
      console.log(`${u.email}: ${error ? `delete failed (${error.message})` : 'deleted'}`);
    }
  }
  await admin.from('events').delete().eq('provider', 'atlas-live-test');
  if (existsSync('.env.live.local')) unlinkSync('.env.live.local');
  process.exit(0);
}

const lines = ['# GENERATED by scripts/live/provision-test-users.mjs — dedicated live TEST accounts. Gitignored; do not commit.'];
for (const u of USERS) {
  const password = randomBytes(18).toString('base64url');
  const existing = await findUser(u.email);
  if (existing) {
    const { error } = await admin.auth.admin.updateUserById(existing.id, { password, email_confirm: true });
    if (error) throw error;
    console.log(`${u.email}: password refreshed`);
  } else {
    const { error } = await admin.auth.admin.createUser({
      email: u.email, password, email_confirm: true,
      user_metadata: { username: u.username, display_name: `Live Test ${u.id.toUpperCase()}` },
    });
    if (error) throw error;
    console.log(`${u.email}: created`);
  }
  const U = u.id.toUpperCase();
  lines.push(`ATLAS_LIVE_${U}_EMAIL=${u.email}`, `ATLAS_LIVE_${U}_PASSWORD=${password}`);
}

const { error: evErr } = await admin.from('events').upsert({
  provider: 'atlas-live-test', external_id: 'live-test-1',
  name: 'Sample: Atlas live-test event (not real)',
  description: 'Development sample used by automated tests. Not a real listing.',
  category: 'Miscellaneous', venue_name: 'Test venue (not real)',
  latitude: 0.5, longitude: -30, timezone: 'UTC',
  start_local_date: new Date(Date.now() + 7 * 86400000).toISOString().slice(0, 10), start_local_time: '20:00',
  source_name: 'Atlas development fixtures', is_dev_fixture: true,
}, { onConflict: 'provider,external_id' });
if (evErr) throw evErr;
console.log('sample test event: upserted (is_dev_fixture=true)');

writeFileSync('.env.live.local', lines.join('\n') + '\n', { mode: 0o600 });
console.log('wrote .env.live.local (gitignored)');
